"""Route planning service for FastAPI applications."""

from __future__ import annotations

from dataclasses import dataclass
from heapq import heappop, heappush
from typing import Dict, List, Mapping, Sequence, Tuple


class RouteCalculationError(Exception):
    """Raised when route calculation fails due to invalid data or constraints."""


class RouteNotFoundError(RouteCalculationError):
    """Raised when no feasible routes exist for the provided constraints."""


@dataclass(frozen=True, slots=True)
class RouteEdge:
    """Represents a directed travel segment in the route graph.

    Attributes:
        destination: Node reached from the source node.
        cost: Monetary cost for traversing the segment.
        time: Travel time for traversing the segment.
    """

    destination: str
    cost: float
    time: float


@dataclass(frozen=True, slots=True)
class RouteConstraints:
    """User constraints used during route search.

    Attributes:
        starting_point: Node where route generation starts.
        max_budget: Maximum allowed total route cost.
        max_time: Maximum allowed total route time.
        max_routes: Maximum number of distinct routes to return.
    """

    starting_point: str
    max_budget: float
    max_time: float
    max_routes: int = 3


@dataclass(frozen=True, slots=True)
class CalculatedRoute:
    """A route candidate generated by the planner.

    Attributes:
        path: Ordered nodes visited in the route.
        total_cost: Sum of travel costs across the path.
        total_time: Sum of travel times across the path.
    """

    path: Tuple[str, ...]
    total_cost: float
    total_time: float


class TravelRouteService:
    """Calculates distinct routes constrained by budget and travel time.

    The service performs a priority-queue traversal over a directed graph,
    prioritizing lower combined cost/time states and pruning dominated states
    to keep the search efficient.
    """

    def __init__(self, graph: Mapping[str, Sequence[RouteEdge]]) -> None:
        """Initialize the service.

        Args:
            graph: Adjacency mapping where keys are node names and values are
                outgoing edges from each node.

        Raises:
            RouteCalculationError: If the graph contains invalid or incomplete
                travel segment data.
        """

        self._graph: Dict[str, Tuple[RouteEdge, ...]] = {
            node: tuple(edges) for node, edges in graph.items()
        }
        self._validate_graph()

    def calculate_routes(self, constraints: RouteConstraints) -> List[CalculatedRoute]:
        """Compute up to three distinct feasible routes.

        Distinct routes are determined by unique ordered node paths.

        Args:
            constraints: User-defined search limits.

        Returns:
            A list of distinct routes ordered by ascending `(cost + time)` score.

        Raises:
            ValueError: If provided constraints are invalid.
            RouteCalculationError: If the starting point is missing.
            RouteNotFoundError: If no feasible route can be generated.
        """

        self._validate_constraints(constraints)

        if constraints.starting_point not in self._graph:
            raise RouteCalculationError(
                f"Starting point '{constraints.starting_point}' does not exist in graph."
            )

        route_limit: int = min(constraints.max_routes, 3)
        priority_queue: List[Tuple[float, float, float, Tuple[str, ...], str]] = [
            (0.0, 0.0, 0.0, (constraints.starting_point,), constraints.starting_point)
        ]
        feasible_routes: List[CalculatedRoute] = []
        seen_paths: set[Tuple[str, ...]] = set()
        pareto_frontier: Dict[str, List[Tuple[float, float]]] = {
            constraints.starting_point: [(0.0, 0.0)]
        }

        while priority_queue and len(feasible_routes) < route_limit:
            _, current_cost, current_time, path, current_node = heappop(priority_queue)

            if len(path) > 1 and path not in seen_paths:
                seen_paths.add(path)
                feasible_routes.append(
                    CalculatedRoute(
                        path=path,
                        total_cost=current_cost,
                        total_time=current_time,
                    )
                )

            for edge in self._graph.get(current_node, ()):
                if edge.destination in path:
                    continue

                next_cost: float = current_cost + edge.cost
                next_time: float = current_time + edge.time

                if next_cost > constraints.max_budget or next_time > constraints.max_time:
                    continue

                next_path: Tuple[str, ...] = (*path, edge.destination)

                if self._is_dominated(edge.destination, next_cost, next_time, pareto_frontier):
                    continue

                self._update_frontier(edge.destination, next_cost, next_time, pareto_frontier)
                next_score: float = next_cost + next_time
                heappush(
                    priority_queue,
                    (next_score, next_cost, next_time, next_path, edge.destination),
                )

        if not feasible_routes:
            raise RouteNotFoundError(
                "No feasible routes found for the given budget/time constraints."
            )

        return feasible_routes

    def _validate_graph(self) -> None:
        """Validate graph integrity and edge values.

        Raises:
            RouteCalculationError: If graph data is missing or contains invalid
                node names or edge metrics.
        """

        if not self._graph:
            raise RouteCalculationError("Graph data is required for route calculation.")

        for node, edges in self._graph.items():
            if not node:
                raise RouteCalculationError("Graph contains an empty node name.")
            for edge in edges:
                if not edge.destination:
                    raise RouteCalculationError(
                        f"Node '{node}' contains an edge with missing destination."
                    )
                if edge.cost < 0 or edge.time < 0:
                    raise RouteCalculationError(
                        f"Node '{node}' has negative cost/time edge values."
                    )
                if edge.destination not in self._graph:
                    raise RouteCalculationError(
                        f"Node '{node}' points to missing destination '{edge.destination}'."
                    )

    def _validate_constraints(self, constraints: RouteConstraints) -> None:
        """Validate user-provided route constraints.

        Args:
            constraints: Constraints to validate.

        Raises:
            ValueError: If any constraint value is invalid.
        """

        if not constraints.starting_point:
            raise ValueError("starting_point must be a non-empty string.")
        if constraints.max_budget < 0:
            raise ValueError("max_budget must be greater than or equal to 0.")
        if constraints.max_time < 0:
            raise ValueError("max_time must be greater than or equal to 0.")
        if constraints.max_routes <= 0:
            raise ValueError("max_routes must be greater than 0.")

    @staticmethod
    def _is_dominated(
        node: str,
        cost: float,
        time: float,
        frontier: Mapping[str, Sequence[Tuple[float, float]]],
    ) -> bool:
        """Check if a state is dominated by an existing state.

        A state is dominated when another state for the same node has both
        lower-or-equal cost and lower-or-equal time.

        Args:
            node: Current node.
            cost: State cumulative cost.
            time: State cumulative time.
            frontier: Best-known states per node.

        Returns:
            True if dominated; otherwise False.
        """

        return any(
            saved_cost <= cost and saved_time <= time
            for saved_cost, saved_time in frontier.get(node, ())
        )

    @staticmethod
    def _update_frontier(
        node: str,
        cost: float,
        time: float,
        frontier: Dict[str, List[Tuple[float, float]]],
    ) -> None:
        """Update Pareto frontier for a node.

        Args:
            node: Node whose frontier must be updated.
            cost: Candidate cumulative cost.
            time: Candidate cumulative time.
            frontier: Mutable frontier mapping.
        """

        entries: List[Tuple[float, float]] = frontier.setdefault(node, [])
        entries[:] = [
            (saved_cost, saved_time)
            for saved_cost, saved_time in entries
            if not (cost <= saved_cost and time <= saved_time)
        ]
        entries.append((cost, time))
